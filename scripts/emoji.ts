import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

// Slack names its emoji after iamcal/emoji-data (https://github.com/iamcal/emoji-data), as `emoji-datasource` ships it.
const SOURCE = new URL("../node_modules/emoji-datasource/emoji.json", import.meta.url)
const TARGET = new URL("../src/generated/emoji.ts", import.meta.url)

interface Entry {
  unified: string
  non_qualified: string | null
  short_name: string
  obsoleted_by?: string
  skin_variations?: Record<string, { unified: string; non_qualified: string | null }>
}

const TONES: Record<string, number> = { "1F3FB": 2, "1F3FC": 3, "1F3FD": 4, "1F3FE": 5, "1F3FF": 6 }

const glyph = (unified: string) => String.fromCodePoint(...unified.split("-").map((hex) => Number.parseInt(hex, 16)))

const names = new Map<string, string>()
const put = (unified: string | null, name: string) => {
  if (unified && !names.has(glyph(unified))) names.set(glyph(unified), name)
}
const entries = (JSON.parse(readFileSync(SOURCE, "utf8")) as Entry[]).filter((one) => !one.obsoleted_by)
for (const one of entries) {
  put(one.unified, one.short_name)
  put(one.non_qualified, one.short_name)
  for (const [tone, variation] of Object.entries(one.skin_variations ?? {})) {
    const level = TONES[tone]
    if (level === undefined) continue
    put(variation.unified, `${one.short_name}::skin-tone-${level}`)
    put(variation.non_qualified, `${one.short_name}::skin-tone-${level}`)
  }
}

const rows = [...names].sort(([one], [other]) => (one < other ? -1 : 1))
const raw = `// Generated by scripts/emoji.ts from emoji-datasource; do not edit.
export const EMOJI_NAMES: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(rows), null, 2)}
`
const text = execFileSync("biome", ["format", `--stdin-file-path=${fileURLToPath(TARGET)}`], {
  input: raw,
  encoding: "utf8",
  maxBuffer: 16 * 1024 * 1024,
})

if (process.argv.includes("--check")) {
  if (readFileSync(TARGET, "utf8") !== text) {
    console.error("src/generated/emoji.ts is out of date: run node --experimental-strip-types scripts/emoji.ts")
    process.exit(1)
  }
} else writeFileSync(TARGET, text)
console.log(`emoji: ${rows.length} names`)
